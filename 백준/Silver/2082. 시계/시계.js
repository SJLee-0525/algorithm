const fs = require('fs');
const input = fs.readFileSync('/dev/stdin').toString().trim().split('\n');

const solution = (input) => {
    const arr = Array.from({ length: 4 }, () => Array());
    const res = Array(4);

    for (let i = 0; i < 5; i++) {
        const line = input[i].split(' ');

        for (let l = 0; l < 4; l++) arr[l].push(line[l].split(''));
    }

    for (let n = 0; n < 4; n++) {
        const isPossible = Array(10).fill(true);

        for (let l = 0; l < 5; l++) {
            for (let e = 0; e < 3; e++) {
                if (arr[n][l][e] === '.') continue;

                for (let k = 0; k < 10; k++) {
                    if (!isPossible[k]) continue; 

                    if (data[k][l][e] === '.') isPossible[k] = false;
                }
            }
        }

        for (let p = 0; p < 10; p++) {
            if (isPossible[p]) {
                res[n] = p;
                break;
            }
        }
    }

    console.log(
        res.slice(0, 2).join('') + ':' + res.slice(2, 4).join('')
    );
}

solution(input);