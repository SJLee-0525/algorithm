/******************************************************************
 * 문제(가정)
 * ---------------------------------------------------------------
 * 길이가 N인 문자열을 만든다.
 *  - 사용 가능한 문자: 0, 1, 2
 *  - 문자 ‘1’은 **연속 세 번** 나오면 안 된다.      (…0111… 불가)
 *  - 문자 ‘2’는 **정확히 한 번**만 등장해야 한다.
 *
 * 위 조건을 만족하는 문자열의 개수를 1,000,000,007 로 나눈 값을 구하라.
 *
 * 알고리즘 개요
 * ---------------------------------------------------------------
 * • DP 한 칸씩 확장: 길이 i → i+1 의 모든 가능 전이만 누적.
 * • 상태(state)는 ➀ 마지막에 연속된 ‘1’의 길이(0,1,2) 와
 *                 ➁ ‘2’를 이미 썼는지 여부(0,1) 로 표현.
 *   ┌─────┬───────────────┐
 *   │ idx │ state 의미    │
 *   ├─────┼───────────────┤
 *   │  0  │ G   : 연속 ‘1’ 길이 0, 2 미사용 여부 k                │
 *   │  1  │ A1  : 연속 ‘1’ 길이 1, 2 미사용 여부 k               │
 *   │  2  │ A2  : 연속 ‘1’ 길이 2, 2 **이미 사용**(k=1 고정)     │
 *   │  3  │ B   : 연속 ‘1’ 길이 0, 2 **이미 사용**(k=1 고정)     │
 *   └─────┴───────────────┘
 *
 *   ※ A2, B 는 정의상 k = 1 일 때만 값이 의미 있다.  
 *      (배열은 편의상 [][0],[][1] 두 칸을 모두 두지만 k=0 인 값은 항상 0)
 *
 * • 전이 표 (현재 → 다음, 괄호는 ‘2’ 사용 플래그 변화)
 *   ┌──────────┬────────────┬────────────┬────────────┐
 *   │ 현재     │ ‘0’ 추가   │ ‘1’ 추가   │ ‘2’ 추가   │
 *   ├──────────┼────────────┼────────────┼────────────┤
 *   │ G(k)     │ G(k)       │ A1(k)      │ A2(1)      │
 *   │ A1(k)    │ G(k)       │ B(k or 1)  │ B(1)       │
 *   │ A2(1)    │ G(1)       │ B(1)       │ —          │
 *   │ B(1)     │ G(1)       │ —          │ —          │
 *   └──────────┴────────────┴────────────┴────────────┘
 *
 *   - ‘1’을 두 번 연속 넣으면 A1 → B 로 바뀌어,
 *     다음에 또 ‘1’을 붙일 수 없게(= 세 번 연속 금지) 만든다.
 *   - ‘2’는 G 또는 A1 에서만 넣을 수 있으며,
 *     넣는 즉시 k = 1 로 고정된다.
 *
 * • 최종 답: 길이 N 에서 k = 1(‘2’를 정확히 한 번 사용) 인
 *            모든 상태(G, A1, A2, B) 의 합.
 *
 * • 복잡도: 시간 O(N) / 메모리 O(1)  (상태 4×2 개만 유지)
 ******************************************************************/

const fs  = require('fs');
const N   = Number(fs.readFileSync('/dev/stdin').toString().trim());
const MOD = 1000000007n;   // BigInt 모듈로 연산

// 상태 인덱스 상수화 ───────────────────────────────────────────
const G  = 0;   // good : 연속 '1' 없음
const A1 = 1;   // 마지막이 '1' 1개
const A2 = 2;   // 마지막이 '1' 2개 (이미 '2' 사용)
const B  = 3;   // '2' 사용 후, 연속 '1' 0개

/******************************************************************
 * cur[s][k] : 길이 i  문자열을
 *             상태 s(0~3), '2' 사용 여부 k(0/1) 로 끝낼 수 있는 가짓수
 * 처음 i = 1   =>  “문자 0 하나” 밖에 만들 수 없으므로
 *                  상태 G, k = 0 만 1 이다.
 ******************************************************************/
let cur = Array.from({ length: 4 }, () => [0n, 0n]);
cur[G][0] = 1n;          // 길이 1, 문자열 "0"

/******************************************************************
 * i = 2 … N 까지 한 글자씩 붙여 가며 DP 갱신
 ******************************************************************/
for (let i = 2; i <= N; i++) {
  // nxt 초기화
  let nxt = Array.from({ length: 4 }, () => [0n, 0n]);

  // === 1) 현재 상태 G(k) 에서 글자 하나 추가 ===================
  for (let k = 0; k < 2; k++) {
    // ‘0’ 추가 → 연속 ‘1’ 초기화, k 그대로
    nxt[G][k]  = (nxt[G][k]  + cur[G][k]) % MOD;

    // ‘1’ 추가 → 연속 ‘1’ = 1, k 그대로
    nxt[A1][k] = (nxt[A1][k] + cur[G][k]) % MOD;

    // ‘2’ 추가 → 연속 ‘1’ = 2 (A2), k 는 1 로 고정
    nxt[A2][1] = (nxt[A2][1] + cur[G][k]) % MOD;
  }

  // === 2) 현재 상태 A1(k) (“…1”) ===============================
  for (let k = 0; k < 2; k++) {
    // ‘0’ 추가 → 연속 ‘1’ 초기화 (G)
    nxt[G][k]  = (nxt[G][k]  + cur[A1][k]) % MOD;

    // ‘1’ 추가 → 두 번째 연속 ‘1’, 상태 B 로 이동
    //            k 유지(‘2’ 아직 안 썼으면 그대로 0)
    nxt[B][k]  = (nxt[B][k]  + cur[A1][k]) % MOD;

    // ‘2’ 추가 → 상태 B 로, k = 1 로 고정
    nxt[B][1]  = (nxt[B][1]  + cur[A1][k]) % MOD;
  }

  // === 3) 현재 상태 A2(1) (“…11”) ==============================
  //        (k 는 1 로만 의미가 있음)
  for (let k = 0; k < 2; k++) {
    // ‘0’ 추가 → 연속 ‘1’ 초기화 (G, k 유지)
    nxt[G][k]  = (nxt[G][k]  + cur[A2][k]) % MOD;

    // ‘1’ 추가 → 세 번째 연속 ‘1’ 방지를 위해 B 로
    nxt[B][k]  = (nxt[B][k]  + cur[A2][k]) % MOD;
    // ‘2’ 는 이미 사용했기 때문에 더 붙일 수 없음
  }

  // === 4) 현재 상태 B(1) (“이미 ‘2’ 사용, …0”) =================
  for (let k = 0; k < 2; k++) {
    // ‘0’ 추가만 허용 → 다시 G(1) 로
    nxt[G][k]  = (nxt[G][k]  + cur[B][k]) % MOD;
  }

  // i 길이 문자열 계산 완료 → cur ← nxt
  cur = nxt;
}

/******************************************************************
 * 답 : 길이 N 에서 k = 1 (정확히 한 번 ‘2’ 사용) 인
 *      모든 상태(G, A1, A2, B) 의 합
 ******************************************************************/
let ans = 0n;
for (let s = 0; s < 4; s++) ans = (ans + cur[s][1]) % MOD;

console.log(ans.toString());
